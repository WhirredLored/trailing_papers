/**
 * Estimate engine — pure functions over a set of estimate lines.
 *
 * No side effects, no database access. Everything the builder shows while the
 * contractor is typing, and everything the server freezes at issue, comes from
 * this module, so the number on the phone and the number in the database are
 * produced by the same code. Money math is delegated to lib/money.ts and
 * lib/totals.ts — this file adds no arithmetic of its own to a dollar value.
 *
 * THREE THINGS LIVE HERE THAT THE TOTALS ENGINE DOES NOT KNOW ABOUT:
 *
 *   1. OPTIONAL LINES. An optional line is displayed on the estimate but does
 *      not count toward any total until it is selected. Filtering happens once,
 *      in `billableLines`, and every total downstream is computed from that.
 *
 *   2. PROFITABILITY. Cost, margin and labour hours are internal — they are
 *      never rendered to a client — so they are computed separately from the
 *      client-facing breakdown rather than bolted onto it.
 *
 *   3. GROUPS. The same rows render as an itemized estimate or as a summary of
 *      group totals. The detail level is a presentation choice at issue time; it
 *      does not change the stored data.
 */

import type { Enums } from '@/types/db'
import {
  type Cents,
  applyMargin,
  applyMarkup,
  multiplyCents,
  percentOfCents,
  subtractCents,
  sumCents,
} from './money'
import { computeTotals, type LineItem, type TotalsBreakdown } from './totals'
import type { TakeoffResult } from './takeoff'

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

/** Aliased from the generated enums so the two cannot drift apart. */
export type EstimateLineKind = Enums<'catalog_item_kind'>
export type EstimateLineUnit = Enums<'catalog_item_unit'>
export type PricingMode = Enums<'estimate_pricing_mode'>
export type AmountMode = Enums<'amount_mode'>
export type DetailLevel = Enums<'estimate_detail_level'>

/** Label used for lines the contractor has not put in a group. */
export const UNGROUPED_LABEL = 'Ungrouped'

/**
 * One line as the builder holds it. This is the shape the pure functions work
 * on; the database row carries the same fields plus identity and ordering.
 */
export interface EstimateLineDraft {
  description: string
  quantity: number
  unit: EstimateLineUnit
  kind: EstimateLineKind
  /** What the client pays per unit. */
  unitPriceCents: Cents
  /** What it costs the contractor per unit — internal only. */
  unitCostCents: Cents
  taxable: boolean
  isOptional: boolean
  isSelected: boolean
  groupLabel: string | null
  /** Set when the line came from the price book. */
  catalogItemId?: string | null
  /** Set, with driverQuantity, when the line was generated by a takeoff. */
  assemblyId?: string | null
  driverQuantity?: number | null
  /** Ties one takeoff's generated lines together. */
  assemblyGroupId?: string | null
  /** The takeoff derivation string, kept so the quantity stays auditable. */
  derivation?: string | null
}

/** The money terms that sit above the lines. Mirrors the estimate columns. */
export interface EstimateTerms {
  taxRateBp: number
  discountMode: AmountMode
  discountValue: number
  depositMode: AmountMode
  depositValue: number
}

export interface EstimateTotals {
  /** The client-facing breakdown, computed over billable lines only. */
  breakdown: TotalsBreakdown
  /**
   * Extended amount for EVERY line in input order, including optional lines
   * that are not selected — those display a price but are excluded from the
   * breakdown above.
   */
  lineExtendedCents: Cents[]
  /** What the unselected optional lines would add if they were all taken. */
  optionalTotalCents: Cents
}

export interface PhaseHours {
  /** The group heading the labour sits under; assemblies name their phase. */
  label: string
  hours: number
}

export interface Profitability {
  /** Cost of the billable lines, at the costs snapshotted onto them. */
  estimatedCostCents: Cents
  /** Pre-tax revenue: subtotal less discount. Tax is not revenue. */
  revenueCents: Cents
  marginCents: Cents
  /** Margin as a share of revenue, in basis points (2000 = 20%). */
  marginBp: number
  /** Labour hours by group, in the order the groups first appear. */
  hoursByPhase: PhaseHours[]
  totalHours: number
}

export interface GroupSummary {
  label: string
  /** Total of the billable lines in this group — what a summary estimate shows. */
  subtotalCents: Cents
  /** Total of this group's unselected optional lines. */
  optionalCents: Cents
  lineCount: number
}

// ---------------------------------------------------------------------------
// Optional lines
// ---------------------------------------------------------------------------

/**
 * Whether a line counts toward the totals.
 *
 * A line that is not optional always counts. An optional line counts only once
 * it has been selected — that is the whole behaviour of an optional line, and
 * it is defined in exactly one place so no caller can get it half right.
 */
export function isBillable(line: EstimateLineDraft): boolean {
  return !line.isOptional || line.isSelected
}

/** The lines that count toward the totals. */
export function billableLines(lines: EstimateLineDraft[]): EstimateLineDraft[] {
  return lines.filter(isBillable)
}

// ---------------------------------------------------------------------------
// Totals
// ---------------------------------------------------------------------------

function toLineItem(line: EstimateLineDraft): LineItem {
  return {
    description: line.description,
    unitPriceCents: line.unitPriceCents,
    quantity: line.quantity,
    taxable: line.taxable,
  }
}

/**
 * Compute the client-facing breakdown plus the per-line and optional figures
 * the builder needs on screen.
 */
export function computeEstimateTotals(
  lines: EstimateLineDraft[],
  terms: EstimateTerms,
): EstimateTotals {
  const billable = billableLines(lines)

  const breakdown = computeTotals({
    lines: billable.map(toLineItem),
    taxRateBp: terms.taxRateBp,
    discountType: terms.discountMode,
    discountValue: terms.discountValue,
    depositType: terms.depositMode,
    depositValue: terms.depositValue,
  })

  // Every line gets an extended amount for display, billable or not.
  const lineExtendedCents = lines.map((line) => multiplyCents(line.unitPriceCents, line.quantity))

  const optionalTotalCents = sumCents(
    lines.filter((line) => !isBillable(line)).map((line) => multiplyCents(line.unitPriceCents, line.quantity)),
  )

  return { breakdown, lineExtendedCents, optionalTotalCents }
}

// ---------------------------------------------------------------------------
// Profitability (internal — never rendered to a client)
// ---------------------------------------------------------------------------

/**
 * Estimated cost, margin, and labour hours by phase.
 *
 * Margin is measured against PRE-TAX revenue (subtotal less discount). Sales tax
 * is collected on behalf of the state and is not the contractor's money, so
 * including it would overstate every job.
 *
 * Hours are the quantities on hour-unit labour lines. A labour line priced by
 * the day contributes cost but not hours — there is no defensible constant to
 * convert one into the other, and inventing one would put a wrong number in
 * front of a contractor scheduling a crew.
 *
 * Phases come from the group label. Assembly takeoffs insert their components
 * under the assembly's name, which is the phase ("demo", "siding", "trim"), so
 * grouping by label is grouping by phase until the phase table lands in C15.
 */
export function computeProfitability(
  lines: EstimateLineDraft[],
  totals: EstimateTotals,
): Profitability {
  const billable = billableLines(lines)

  const estimatedCostCents = sumCents(
    billable.map((line) => multiplyCents(line.unitCostCents, line.quantity)),
  )

  const revenueCents = subtractCents(
    totals.breakdown.subtotalCents,
    totals.breakdown.discountCents,
  )
  const marginCents = subtractCents(revenueCents, estimatedCostCents)
  const marginBp = percentOfCents(marginCents, revenueCents)

  // Insertion-ordered so the phases read in the order they appear on the estimate.
  const byPhase = new Map<string, number>()
  for (const line of billable) {
    if (line.kind !== 'labor' || line.unit !== 'hour') continue
    const label = line.groupLabel?.trim() || UNGROUPED_LABEL
    byPhase.set(label, (byPhase.get(label) ?? 0) + line.quantity)
  }

  const hoursByPhase: PhaseHours[] = [...byPhase.entries()].map(([label, hours]) => ({
    label,
    // Hours are a physical quantity, not money; round to a sensible display
    // precision rather than carrying float noise through the panel.
    hours: Math.round(hours * 100) / 100,
  }))

  const totalHours = Math.round(hoursByPhase.reduce((sum, p) => sum + p.hours, 0) * 100) / 100

  return { estimatedCostCents, revenueCents, marginCents, marginBp, hoursByPhase, totalHours }
}

// ---------------------------------------------------------------------------
// Groups (itemized vs summary presentation)
// ---------------------------------------------------------------------------

/**
 * Roll the lines up into their groups.
 *
 * A summary estimate publishes these totals and nothing else — no quantities,
 * no unit prices. Contractors often do not want to publish what they pay for
 * material, and this is how that is supported without storing the estimate any
 * differently: same rows, different rendering.
 */
export function summarizeGroups(lines: EstimateLineDraft[]): GroupSummary[] {
  // Collect first, add once through sumCents — no `+` on a money value outside
  // lib/money.ts.
  const buckets = new Map<string, { billable: Cents[]; optional: Cents[]; lineCount: number }>()

  for (const line of lines) {
    const label = line.groupLabel?.trim() || UNGROUPED_LABEL
    let bucket = buckets.get(label)
    if (!bucket) {
      bucket = { billable: [], optional: [], lineCount: 0 }
      buckets.set(label, bucket)
    }
    const extended = multiplyCents(line.unitPriceCents, line.quantity)
    if (isBillable(line)) {
      bucket.billable.push(extended)
    } else {
      bucket.optional.push(extended)
    }
    bucket.lineCount += 1
  }

  return [...buckets.entries()].map(([label, bucket]) => ({
    label,
    subtotalCents: sumCents(bucket.billable),
    optionalCents: sumCents(bucket.optional),
    lineCount: bucket.lineCount,
  }))
}

// ---------------------------------------------------------------------------
// Pricing
// ---------------------------------------------------------------------------

/**
 * Derive a selling price from a cost.
 *
 * The markup/margin toggle is the estimate-level choice of which of these two
 * genuinely different calculations applies. lib/money.ts keeps them separate;
 * this just routes to the one the estimate is set to.
 */
export function priceFromCost(costCents: Cents, mode: PricingMode, bp: number): Cents {
  return mode === 'margin' ? applyMargin(costCents, bp) : applyMarkup(costCents, bp)
}

// ---------------------------------------------------------------------------
// Assembly takeoff → estimate lines
// ---------------------------------------------------------------------------

/** The catalog facts a takeoff component needs to become a priced line. */
export interface TakeoffLineSource {
  catalogItemId: string
  kind: EstimateLineKind
  unit: EstimateLineUnit
  unitCostCents: Cents
  taxable: boolean
}

export interface TakeoffInsertOptions {
  assemblyId: string
  /** Groups the generated lines together; the caller supplies a fresh uuid. */
  assemblyGroupId: string
  /** Heading the generated lines sit under. Defaults to the assembly name. */
  groupLabel?: string
  pricingMode: PricingMode
  pricingBp: number
  /** Insert the whole group as optional (an "if you also want…" section). */
  isOptional?: boolean
}

/**
 * Convert a computed takeoff into estimate lines.
 *
 * `sources` must be in the same order as `takeoff.components` — they are the
 * catalog facts for each component, which the takeoff result does not carry.
 * A length mismatch is a programming error and throws rather than silently
 * pricing a component against the wrong catalog item.
 *
 * The derivation string travels onto the line. That is the evidence chain: six
 * months later the contractor can show exactly why the estimate said 5 squares.
 */
export function linesFromTakeoff(
  takeoff: TakeoffResult,
  sources: TakeoffLineSource[],
  options: TakeoffInsertOptions,
): EstimateLineDraft[] {
  if (sources.length !== takeoff.components.length) {
    throw new TypeError(
      `Takeoff has ${takeoff.components.length} components but ${sources.length} catalog sources were supplied.`,
    )
  }

  const groupLabel = options.groupLabel?.trim() || takeoff.assemblyName

  return takeoff.components.map((component, index) => {
    // Checked above; the index is in range.
    const source = sources[index] as TakeoffLineSource
    return {
      description: component.name,
      quantity: component.purchaseQuantity,
      unit: source.unit,
      kind: source.kind,
      unitPriceCents: priceFromCost(source.unitCostCents, options.pricingMode, options.pricingBp),
      unitCostCents: source.unitCostCents,
      taxable: source.taxable,
      isOptional: options.isOptional ?? false,
      isSelected: false,
      groupLabel,
      catalogItemId: source.catalogItemId,
      assemblyId: options.assemblyId,
      driverQuantity: takeoff.driverQuantity,
      assemblyGroupId: options.assemblyGroupId,
      derivation: component.derivation,
    }
  })
}
